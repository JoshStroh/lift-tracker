const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
export const exId = (name) => 'ex-' + slug(name);

export const BUILTIN_EXERCISES = Object.entries(DATA).flatMap(([category, rows]) =>
  rows.map(([name, equip, kind, pattern, photo, aliases = '', flags = '']) => {
    const f = flags.split(/\s+/).filter(Boolean);
    const lvl = f.find((x) => /^L\d$/.test(x));
    return {
      id: exId(name), type: 'exercise', name, category, equip, kind, pattern,
      photo: photo || '', aliases, builtin: true,
      uni: f.includes('u') || f.includes('s'),
      sided: f.includes('s'),
      level: lvl ? +lvl.slice(1) : 0,
    };
  })
);

export const isCalisthenics = (ex) => CALI_EQUIPMENT.has(ex.equip);
